// Writes docs/engine/INDEX.md: every exported name of every engine file, so module authors can find a function fast.
import { readdir, readFile, writeFile } from 'node:fs/promises';
const root = 'src/engine';
let out = '# Engine export index\n\nGenerated by `node tools/engine-index.mjs`. Open the source file for arguments, units and references.\n';
for (const area of (await readdir(root)).sort()) {
  out += `\n## ${area}\n\n`;
  for (const f of (await readdir(`${root}/${area}`)).filter((x) => x.endsWith('.js')).sort()) {
    const src = await readFile(`${root}/${area}/${f}`, 'utf8');
    const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|class|let)\s+([A-Za-z0-9_$]+)/gm)].map((m) => m[1]);
    out += `- \`${area}/${f}\` — ${names.join(', ') || '(no named exports)'}\n`;
  }
}
await writeFile('docs/engine/INDEX.md', out);
console.log(out.length, 'chars');
